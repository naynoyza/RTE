// =====================================================================================================
// ThaiText — ข้อความที่แสดงภาษาไทยถูกต้อง
// -----------------------------------------------------------------------------------------------------
// หน้าที่ : เหมือน Text ปกติ แต่ทุกครั้งที่ตั้งข้อความ จะส่งผ่าน UIKit.FixThai ก่อน
//           (ย้ายวรรณยุกต์ที่ซ้อนบนสระบนไปใช้ตัวยกสูง จะได้ไม่ทับกัน)
// ใช้โดย  : UIKit.Label สร้างข้อความทุกตัวในเกมด้วยคลาสนี้
// =====================================================================================================
using UnityEngine.UI;

namespace RTE
{
    public class ThaiText : Text
    {
        public override string text
        {
            get => base.text;
            set => base.text = UIKit.FixThai(value);
        }
    }
}
